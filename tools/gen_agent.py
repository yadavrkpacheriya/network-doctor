#!/usr/bin/env python3
"""Generate desktop/nd_agent.py from the endpoint agent files.

Network Doctor (frozen .exe) carries the agent as data so it can PUBLISH the newest version to the IT share,
from where every PC's agent self-updates. The endpoint/*.ps1 and *.cmd files stay the single source of truth;
this script embeds them into a Python module, and tests/test_agent_publish.py asserts they never drift.

Run from the repo root:  python3 tools/gen_agent.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENDPOINT = os.path.join(ROOT, "endpoint")
OUT = os.path.join(ROOT, "desktop", "nd_agent.py")

# Files the PC pulls on a self-update (must match Update-Self in networkdoctor-agent.ps1).
FILES = ["networkdoctor-agent.ps1", "fix-launch.cmd"]


def agent_version(ps1_text):
    m = re.search(r'\$AgentVersion\s*=\s*"([0-9][0-9.]*)"', ps1_text)
    if not m:
        raise SystemExit("could not find $AgentVersion in networkdoctor-agent.ps1")
    return m.group(1)


def main():
    files = {}
    for name in FILES:
        with open(os.path.join(ENDPOINT, name), "r", encoding="utf-8", newline="") as f:
            files[name] = f.read()
    version = agent_version(files["networkdoctor-agent.ps1"])

    parts = ['# -*- coding: utf-8 -*-',
             '"""AUTO-GENERATED by tools/gen_agent.py from endpoint/ - do not edit by hand.',
             '',
             'Carries the PC agent so Network Doctor can PUBLISH the newest version to the IT share',
             '(<endpoint_dir>/agent-dist/), from where every PC self-updates. Regenerate after editing the',
             'endpoint files:  python3 tools/gen_agent.py  (a test asserts this file stays in sync)."""',
             'import os',
             '',
             'AGENT_VERSION = %r' % version,
             '',
             'FILES = {']
    for name in FILES:
        parts.append('    %r: %r,' % (name, files[name]))
    parts.append('}')
    parts.append('')
    parts.append('''
def publish(endpoint_dir):
    """Write the embedded agent + a version.txt into <endpoint_dir>/agent-dist/ so every PC's agent self-updates
    to this version. Overwrites only when this version is newer or the files are missing/changed. Best-effort:
    returns the version written, or None if the folder is not writable. Never raises."""
    try:
        if not endpoint_dir:
            return None
        dist = os.path.join(endpoint_dir, "agent-dist")
        os.makedirs(dist, exist_ok=True)
        ver_path = os.path.join(dist, "version.txt")
        current = ""
        try:
            with open(ver_path, "r", encoding="utf-8") as f:
                current = f.read().strip()
        except OSError:
            current = ""
        if current and _ge(current, AGENT_VERSION):
            # a same-or-newer master is already there (another IT PC, or this version) - nothing to push
            return current
        for name, text in FILES.items():
            with open(os.path.join(dist, name), "w", encoding="utf-8", newline="") as f:
                f.write(text)
        with open(ver_path, "w", encoding="utf-8") as f:
            f.write(AGENT_VERSION)
        return AGENT_VERSION
    except Exception:
        return None


def _ge(a, b):
    """a >= b for dotted numeric versions, without packaging deps."""
    def t(v):
        out = []
        for p in str(v).split("."):
            try:
                out.append(int(p))
            except ValueError:
                out.append(0)
        return out
    return t(a) >= t(b)
'''.strip('\n'))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts) + "\n")
    print("wrote", OUT, "agent version", version, "(%d files)" % len(FILES))


if __name__ == "__main__":
    main()
